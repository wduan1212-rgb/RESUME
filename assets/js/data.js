function inferOrientation(work) {
  if (work.orientation) return work.orientation;
  if (work.type === "pdf-archive" || work.type === "exhibition-board") return "vertical";
  if (work.type === "website-recording") return "horizontal";
  if (work.format && work.format.includes("9:16")) return "vertical";
  return "horizontal";
}

function inferLayout(work) {
  if (work.layout) return work.layout;
  if (work.type === "pdf-archive") return "pdf";
  if (work.type === "exhibition-board") return "board";
  if (work.type === "website-recording") return "browser";
  return inferOrientation(work) === "vertical" ? "phone" : "wide";
}

function inferDisplayGroup(work) {
  if (work.displayGroup) return work.displayGroup;
  if (work.year === 2024) return "archive-2024";
  if (work.type === "exhibition-board") return "timeline-2025-board";
  if (work.year === 2025) return "timeline-2025-dragon";
  if (work.year === 2026 && inferOrientation(work) === "vertical") return "timeline-2026-vertical";
  if (work.year === 2026) return "timeline-2026-horizontal";
  return "works-horizontal";
}

